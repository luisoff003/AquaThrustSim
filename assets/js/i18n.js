/**
 * AquaThrust — translations (English / Mexican Spanish).
 * t('key', {var}) looks up the current language, falling back to English.
 */

export const LANGS = { en: 'English', es: 'Español' };
let current = 'en';

export function setLang(l) {
  current = LANGS[l] ? l : 'en';
}
export function getLang() {
  return current;
}
/** Number-format locale for the current language. */
export function loc() {
  return current === 'es' ? 'es-MX' : 'en-US';
}

export function detectLang(pref) {
  if (pref && LANGS[pref]) return pref;
  try {
    const saved = localStorage.getItem('aquathrust-lang');
    if (saved && LANGS[saved]) return saved;
  } catch {
    /* storage blocked */
  }
  return (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function rememberLang(l) {
  try {
    localStorage.setItem('aquathrust-lang', l);
  } catch {
    /* ignore */
  }
}

export function t(key, vars) {
  let s = STR[current][key];
  if (s === undefined) s = STR.en[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

